
/**
 * generate-config.js
 * Generates XiaoZhi board config.h and sdkconfig.defaults.
 */

const fs = require('fs');
const path = require('path');

function main(cfg) {
  const board = cfg.board || 'bread-compact-wifi';
  const chip = cfg.chip || 'esp32s3';

  const xiaozhiRoot = path.resolve(__dirname, '..', 'xiaozhi-esp32');
  const boardDir = path.join(xiaozhiRoot, 'main', 'boards', board);
  const boardConfigH = path.join(boardDir, 'config.h');

  if (!fs.existsSync(boardConfigH)) {
    throw new Error(`Board "${board}" not found: ${boardConfigH}`);
  }

  // 1. Generate board config.h
  let configH = fs.readFileSync(boardConfigH, 'utf8');

  if (cfg.pins) {
    configH = applyPinOverrides(configH, cfg.pins);
  }

  if (cfg.onboard_led === false) {
    configH = configH.replace(
      /^#define BUILTIN_LED_GPIO\b/gm,
      '// #define BUILTIN_LED_GPIO'
    );
  }

  if (cfg.extra_pins) {
    let extra = '\n// Extra pins from xiaozhi-builder\n';

    for (const [name, gpio] of Object.entries(cfg.extra_pins)) {
      if (gpio !== null && gpio !== undefined) {
        extra += `#define ${name.toUpperCase()}_GPIO GPIO_NUM_${gpio}\n`;
      }
    }

    configH += extra;
  }

  fs.writeFileSync(boardConfigH, configH);
  console.log('Generated board config.h');

  // 2. Load ESP-IDF defaults
  let sdkdefaults = '';

  const rootDefaults = path.join(xiaozhiRoot, 'sdkconfig.defaults');

  if (fs.existsSync(rootDefaults)) {
    sdkdefaults = fs.readFileSync(rootDefaults, 'utf8');
  }

  const chipDefaults = path.join(
    xiaozhiRoot,
    `sdkconfig.defaults.${chip}`
  );

  if (fs.existsSync(chipDefaults)) {
    sdkdefaults += '\n# Chip-specific defaults\n';
    sdkdefaults += fs.readFileSync(chipDefaults, 'utf8');
  }

  // 3. Board selection
  sdkdefaults += '\n# Generated by xiaozhi-builder\n';
  sdkdefaults += `# Board: ${board}\n`;
  sdkdefaults += `CONFIG_BOARD_TYPE_${board.toUpperCase().replace(/-/g, '_')}=y\n`;

  // 4. Language
  const langMap = {
    zh_CN: 'LANGUAGE_ZH_CN',
    zh_TW: 'LANGUAGE_ZH_TW',
    en_US: 'LANGUAGE_EN_US',
    ja_JP: 'LANGUAGE_JA_JP',
    ko_KR: 'LANGUAGE_KO_KR',
    vi_VN: 'LANGUAGE_VI_VN',
    th_TH: 'LANGUAGE_TH_TH',
    de_DE: 'LANGUAGE_DE_DE',
    fr_FR: 'LANGUAGE_FR_FR',
    es_ES: 'LANGUAGE_ES_ES',
    it_IT: 'LANGUAGE_IT_IT',
    ru_RU: 'LANGUAGE_RU_RU'
  };

  if (cfg.language) {
    const lang = langMap[cfg.language] || 'LANGUAGE_EN_US';
    sdkdefaults += `CONFIG_${lang}=y\n`;
  }

  // 5. OLED display
  if (cfg.display === 'ssd1306_128x64') {
    sdkdefaults += '\n# OLED Display Selection\n';
    sdkdefaults += 'CONFIG_OLED_SSD1306_128X64=y\n';
    sdkdefaults += '# CONFIG_OLED_SSD1306_128X32 is not set\n';
    sdkdefaults += '# CONFIG_OLED_SH1106_128X64 is not set\n';
  }

  // 6. Remove inherited flash-size selections
  sdkdefaults = sdkdefaults.replace(
    /^#?\s*CONFIG_ESPTOOLPY_FLASHSIZE_(?:1MB|2MB|4MB|8MB|16MB|32MB|64MB|128MB)(?:=.*)?\r?\n/gm,
    ''
  );

  // Remove inherited partition table selections
  sdkdefaults = sdkdefaults.replace(
    /^#?\s*CONFIG_PARTITION_TABLE_CUSTOM(?:=.*)?\r?\n/gm,
    ''
  );

  sdkdefaults = sdkdefaults.replace(
    /^#?\s*CONFIG_PARTITION_TABLE_CUSTOM_FILENAME=.*\r?\n/gm,
    ''
  );

  // 7. Force ESP32-S3 4MB flash configuration
  sdkdefaults += '\n# ESP32-S3FH4R2 - 4MB Flash Configuration\n';
  sdkdefaults += 'CONFIG_ESPTOOLPY_FLASHSIZE_4MB=y\n';
  sdkdefaults += '# CONFIG_ESPTOOLPY_FLASHSIZE_16MB is not set\n';
  sdkdefaults += 'CONFIG_PARTITION_TABLE_CUSTOM=y\n';
  sdkdefaults += 'CONFIG_PARTITION_TABLE_CUSTOM_FILENAME="partitions/v2/4m.csv"\n';

  // Write generated defaults
  fs.writeFileSync(
    path.join(xiaozhiRoot, 'sdkconfig.defaults'),
    sdkdefaults
  );

  console.log('Generated sdkconfig.defaults');

  // 8. Save build metadata
  const meta = {
    board,
    chip,
    language: cfg.language || 'en_US',
    display: cfg.display || null,
    pins: cfg.pins || {},
    generatedAt: new Date().toISOString()
  };

  fs.writeFileSync(
    path.join(xiaozhiRoot, '.xiaozhi-builder.json'),
    JSON.stringify(meta, null, 2)
  );

  console.log('Build configuration generated successfully.');
}

function applyPinOverrides(source, pins) {
  const pinMap = {
    mic_ws: 'AUDIO_I2S_MIC_GPIO_WS',
    mic_sck: 'AUDIO_I2S_MIC_GPIO_SCK',
    mic_din: 'AUDIO_I2S_MIC_GPIO_DIN',
    spk_dout: 'AUDIO_I2S_SPK_GPIO_DOUT',
    spk_bclk: 'AUDIO_I2S_SPK_GPIO_BCLK',
    spk_lrck: 'AUDIO_I2S_SPK_GPIO_LRCK',
    i2s_ws: 'AUDIO_I2S_GPIO_WS',
    i2s_bclk: 'AUDIO_I2S_GPIO_BCLK',
    i2s_din: 'AUDIO_I2S_GPIO_DIN',
    i2s_dout: 'AUDIO_I2S_GPIO_DOUT',
    led: 'BUILTIN_LED_GPIO',
    boot_btn: 'BOOT_BUTTON_GPIO',
    touch_btn: 'TOUCH_BUTTON_GPIO',
    vol_up_btn: 'VOLUME_UP_BUTTON_GPIO',
    vol_down_btn: 'VOLUME_DOWN_BUTTON_GPIO',
    lamp: 'LAMP_GPIO',
    display_sda: 'DISPLAY_SDA_PIN',
    display_scl: 'DISPLAY_SCL_PIN'
  };

  let result = source;

  for (const [key, macro] of Object.entries(pinMap)) {
    if (pins[key] !== undefined && pins[key] !== null) {
      const regex = new RegExp(`(#define ${macro}\\s+)\\w+`, 'g');

      result = result.replace(
        regex,
        `$1GPIO_NUM_${pins[key]}`
      );
    }
  }

  if (pins.display_width !== undefined) {
    result = result.replace(
      /#define DISPLAY_WIDTH\s+\d+/,
      `#define DISPLAY_WIDTH ${pins.display_width}`
    );
  }

  if (pins.display_height !== undefined) {
    result = result.replace(
      /#define DISPLAY_HEIGHT\s+\d+/,
      `#define DISPLAY_HEIGHT ${pins.display_height}`
    );
  }

  return result;
}

// Read JSON configuration
try {
  const inputFile = process.argv[2];

  if (!inputFile) {
    throw new Error('Missing configuration JSON file argument.');
  }

  const cfg = JSON.parse(fs.readFileSync(inputFile, 'utf8'));
  main(cfg);
} catch (error) {
  console.error('Configuration generation failed:');
  console.error(error.stack || error.message);
  process.exit(1);
}
